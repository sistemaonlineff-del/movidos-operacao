import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { test } from 'node:test'
import { chromium } from 'playwright'
import { startDropRegistrationHarness } from './drop-registration-harness.mjs'

test('real components and API: explicit geolocation, synthetic photos, incomplete retry, private review and INTERESSADO approval',async()=>{
  const harness=await startDropRegistrationHarness()
  const browser=await chromium.launch({channel:'msedge',headless:true})
  try{
    const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,geolocation:{latitude:-23.5,longitude:-46.3},permissions:['geolocation']})
    const errors=[]
    let loseResponse=false
    await context.route('**/*',async route=>{
      const request=route.request(),url=new URL(request.url())
      if(url.origin!==harness.base)return route.abort()
      if(loseResponse&&url.pathname==='/api/drop-registration'&&request.postDataJSON()?.mode==='submit-public'){
        loseResponse=false;await route.fetch();return route.abort('failed')
      }
      return route.continue()
    })
    const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message))
    await page.goto(`${harness.base}/cadastrar-drop`)
    await page.getByRole('heading',{name:'Pre-cadastro Drop',exact:true}).waitFor()
    assert.equal(await page.locator('#public-drop-latitude').inputValue(),'')
    assert.equal(harness.state.requests.length,0)
    await page.getByRole('button',{name:'Autorizar localizacao atual'}).click()
    await page.getByText('Localizacao obtida.',{exact:false}).waitFor()
    assert.equal(await page.locator('#public-drop-latitude').inputValue(),'-23.5000000')
    const fields={name:'Drop Browser',responsible:'Pessoa Sintetica',phone:'11999999999',email:'teste@example.invalid',address:'Rua Sintetica',address_number:'10',municipality:'Suzano',postal_code:'08600000'}
    assert.equal(await page.locator('#public-drop-pix_key').getAttribute('required'),null)
    for(const[field,value]of Object.entries(fields))await page.locator(`#public-drop-${field}`).fill(value)
    await page.locator('#public-drop-state').selectOption('SP')
    const png=await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=640;canvas.height=480;const context=canvas.getContext('2d');context.fillStyle='#187c78';context.fillRect(0,0,640,480);context.fillStyle='#ffffff';context.fillRect(100,80,440,280);context.fillStyle='#d86e48';context.fillRect(240,190,160,170);return canvas.toDataURL('image/png').split(',')[1]})
    await page.getByLabel('Fotos do Drop',{exact:true}).setInputFiles({name:'fachada.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')})
    await page.getByLabel('Legenda da foto 1').fill('Fachada sintetica')
    await page.getByRole('checkbox').check()
    await mkdir('tmp/drop-registration/screenshots',{recursive:true})
    await page.locator('.dr-photos').screenshot({path:'tmp/drop-registration/screenshots/public-photo-mobile.png'})
    harness.state.failUpload=true
    await page.getByRole('button',{name:'Enviar pre-cadastro',exact:true}).click()
    await page.getByRole('alert').filter({hasText:'Envio incompleto'}).waitFor()
    assert.equal(harness.state.records[0].status,'uploading');assert.equal(harness.state.dropWrites,0)
    assert.equal(await page.locator('#public-drop-name').isDisabled(),true)
    const protocol=harness.state.records[0].id
    harness.state.failUpload=false;loseResponse=true
    await page.getByRole('button',{name:'Repetir envio com mesmo protocolo'}).click()
    await page.getByRole('alert').filter({hasText:'Conexao interrompida'}).waitFor()
    assert.equal(harness.state.records[0].status,'pending');assert.equal(harness.state.records.length,1)
    await page.getByRole('button',{name:'Repetir envio com mesmo protocolo'}).click()
    await page.getByRole('heading',{name:'Pre-cadastro recebido'}).waitFor()
    assert.equal(harness.state.records.length,1);assert.equal(harness.state.records[0].id,protocol);assert.equal(harness.state.records[0].status,'pending');assert.equal(harness.state.dropWrites,0)
    assert.equal(harness.state.records[0].snapshot.status,undefined);assert.equal(harness.state.records[0].snapshot.is_active,undefined)
    assert.equal(harness.state.files.size,1);assert.match(harness.state.lastIpKey,/^[a-f0-9]{64}$/)
    assert.equal((await page.evaluate(()=>Object.keys(sessionStorage).filter(key=>key.startsWith('movidos-public')).map(key=>sessionStorage.getItem(key)))).join(''),protocol)
    await mkdir('tmp/drop-registration/screenshots',{recursive:true})
    await page.screenshot({path:'tmp/drop-registration/screenshots/public-receipt-mobile.png',fullPage:true})
    await page.goto(`${harness.base}/review`)
    await page.getByRole('button',{name:'Revisar Drop Browser'}).click()
    assert.equal(await page.getByRole('button',{name:'Aprovar sem ativar'}).isDisabled(),true)
    await page.locator('#review-drop-responsible').fill('Pessoa Revisada')
    await page.getByRole('button',{name:'Salvar revisao',exact:true}).click()
    await page.getByRole('status').filter({hasText:'Revisao salva'}).waitFor()
    assert.equal(harness.state.dropWrites,0)
    await page.getByRole('button',{name:'Revisar Drop Browser'}).click()
    assert.equal(await page.locator('#review-drop-responsible').inputValue(),'Pessoa Revisada')
    await page.getByRole('button',{name:'Ver fotos privadas'}).click()
    await page.waitForFunction(()=>{const image=document.querySelector('.dr-review-editor .dr-gallery img');return image&&image.naturalWidth===640})
    assert.ok(harness.state.requests.some(request=>request.path.includes('/storage/v1/object/sign/')))
    await page.getByRole('button',{name:'Conferir duplicados'}).click()
    await page.getByText('Nenhuma correspondencia encontrada',{exact:true}).waitFor()
    const dimensions=await page.evaluate(()=>({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}))
    assert.equal(await page.locator('meta[name="viewport"]').getAttribute('content'),'width=980')
    assert.equal(dimensions.width,980)
    assert.ok(dimensions.scroll<=dimensions.width+1,JSON.stringify(dimensions))
    await page.screenshot({path:'tmp/drop-registration/screenshots/review-mobile.png',fullPage:true})
    page.once('dialog',dialog=>dialog.accept())
    await page.getByRole('button',{name:'Aprovar sem ativar'}).click()
    await page.getByRole('status').filter({hasText:'Drop criado como INTERESSADO'}).waitFor()
    assert.equal(harness.state.dropWrites,1);assert.equal(harness.state.records[0].status,'approved')
    await page.getByLabel('Status',{exact:true}).selectOption('approved')
    await page.getByRole('button',{name:'Revisar Drop Browser'}).click()
    assert.equal(await page.getByRole('button',{name:'Aprovar sem ativar'}).count(),0)
    assert.equal(await page.locator('#review-drop-name').isDisabled(),true)
    assert.equal(errors.length,0,errors.join('\n'))
    const denied=await browser.newContext({viewport:{width:360,height:800}})
    await denied.route('**/*',route=>new URL(route.request().url()).origin===harness.base?route.continue():route.abort())
    await denied.addInitScript(()=>{globalThis.__dropTest={access:{profile:{role:'operador',is_active:true},permissions:{cadastros_view:true},loading:false}}})
    const locked=await denied.newPage();await locked.goto(`${harness.base}/review`)
    await locked.getByRole('heading',{name:'Acesso restrito'}).waitFor()
    assert.equal(await locked.getByRole('table').count(),0)
    await locked.goto(`${harness.base}/cadastrar-drop`)
    await locked.getByRole('button',{name:'Autorizar localizacao atual'}).click()
    await locked.getByText('Localizacao nao autorizada ou indisponivel.',{exact:false}).waitFor()
    await locked.locator('#public-drop-latitude').fill('-23.5');await locked.locator('#public-drop-longitude').fill('-46.3')
    assert.equal(await locked.locator('#public-drop-latitude').inputValue(),'-23.5')
    await locked.screenshot({path:'tmp/drop-registration/screenshots/public-form-360.png',fullPage:true})
    await locked.evaluate(()=>globalThis.__dropTestUnmount())
    assert.equal(await locked.locator('meta[name="viewport"]').getAttribute('content'),'width=980')
    const desktop=await browser.newPage({viewport:{width:1440,height:1000}})
    await desktop.route('**/*',route=>new URL(route.request().url()).origin===harness.base?route.continue():route.abort())
    await desktop.goto(`${harness.base}/review`);await desktop.getByRole('heading',{name:'Pre-cadastros de Drop'}).waitFor()
    await desktop.screenshot({path:'tmp/drop-registration/screenshots/review-desktop.png',fullPage:true})
    const webp=await desktop.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=20;canvas.height=10;canvas.getContext('2d').fillRect(0,0,20,10);return canvas.toDataURL('image/webp').split(',')[1]})
    const webpReceipt=await desktop.evaluate(async({webp,snapshot})=>{
      const response=await fetch('/api/drop-registration',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({mode:'submit-public',clientId:crypto.randomUUID(),consent:true,snapshot,photos:[{content:webp,fileName:'webp.webp'}]})});return{status:response.status,body:await response.json()}
    },{webp,snapshot:harness.state.records[0].snapshot})
    assert.equal(webpReceipt.status,200);assert.equal(webpReceipt.body.status,'pending');assert.equal(harness.state.dropWrites,1)
  }finally{await browser.close();await harness.close()}
})